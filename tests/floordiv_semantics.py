# // and //= on int and float, CPython's floor semantics (issues/211).
a = [-7, 7, -6, 6, 0, -1, 1]
print([v // 3 for v in a], [v // -3 for v in a])
print([v // 2.0 for v in a], [v // -2.5 for v in a])
print([v * 1.5 // 2 for v in a], [v * 1.5 // -2 for v in a])
print(-9223372036854775807 // (10 ** 18), 9223372036854775807 // -(10 ** 18), 9223372036854775807 // 10 ** 18, -9223372036854775807 // 7)
x = -7
x //= 3
y = 7
y //= -2
z = -9223372036854775807
z //= 10 ** 18
f = -7.0
f //= 2.0
g = 7.5
g //= -2
print(x, y, z, f, g)
print(divmod(-7, 3), divmod(7, -3), divmod(-7.5, 2))
print(-1.0 // -2.5, 1.0 // -2.5, -1.0 // 2.5, 0.0 // -3.0, -0.0 // 3.0, 7.0 // 0.1, -7.0 // 0.1, 1e308 // 1e-308)
